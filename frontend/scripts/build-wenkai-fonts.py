"""Slice LXGW WenKai into woff2 pieces with a unicode-range @font-face each (ADR 0059).

The browser only downloads the pieces whose characters appear on the page. Run from
the frontend directory after downloading the release TTFs into an empty directory:

    gh release download v1.530 -R lxgw/LxgwWenKai -D /tmp/wenkai \\
        -p LXGWWenKai-Regular.ttf -p LXGWWenKai-Medium.ttf
    uv run --no-project --with fonttools --with brotli \\
        python -I scripts/build-wenkai-fonts.py /tmp/wenkai

Pieces, the same for both weights:
  latin    English with diacritics, IPA, punctuation, currency, arrows
  symbols  other non-CJK glyphs below U+2E80 (Greek, Cyrillic, math, boxes)
  ui       Han characters and CJK punctuation used by the zh-CN interface strings
  hot-N    remaining characters ranked by frequency in docs/ (Chinese prose), 150 each
  gb-N     the rest of GB2312, in code order, 200 each
Characters outside these fall back to the system Chinese fonts in globals.css.
"""

import io
import json
import re
import shutil
import sys
from collections import Counter
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

FRONTEND = Path(__file__).resolve().parent.parent
REPO = FRONTEND.parent
OUT_DIR = FRONTEND / "public" / "fonts" / "wenkai"
CSS_PATH = FRONTEND / "src" / "app" / "wenkai.css"
URL_PREFIX = "/fonts/wenkai"
FAMILY = "LXGW WenKai"
# Regular stands in for light weights, Medium for semibold / bold (WenKai has no Bold).
WEIGHTS = [("Regular", "regular", "100 449"), ("Medium", "medium", "450 900")]
HOT_SIZE = 150
GB_SIZE = 200
# Latin with diacritics, IPA, general punctuation, currency, letterlike, arrows.
LATIN_BLOCKS = [(0x0000, 0x036F), (0x1D00, 0x1DBF), (0x1E00, 0x1EFF), (0x2000, 0x21FF)]


def is_cjk(cp: int) -> bool:
    return cp >= 0x2E80


def gb2312_chars() -> list[str]:
    chars = []
    for hi in range(0xA1, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                chars.append(bytes([hi, lo]).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    return chars


def zh_ui_text() -> str:
    def strings(node: object) -> list[str]:
        if isinstance(node, dict):
            return [s for v in node.values() for s in strings(v)]
        return [node] if isinstance(node, str) else []

    data = json.loads((FRONTEND / "messages" / "zh-CN.json").read_text("utf-8"))
    return "".join(strings(data))


def docs_frequency() -> Counter[str]:
    counter: Counter[str] = Counter()
    for path in sorted((REPO / "docs").rglob("*.md")):
        counter.update(re.findall(r"[一-鿿]", path.read_text("utf-8")))
    return counter


def is_latin(cp: int) -> bool:
    return any(lo <= cp <= hi for lo, hi in LATIN_BLOCKS)


def plan_pieces(cmap: set[int]) -> list[tuple[str, list[int]]]:
    latin = sorted(cp for cp in cmap if is_latin(cp))
    symbols = sorted(cp for cp in cmap if not is_latin(cp) and not is_cjk(cp))
    cjk_punct = [cp for cp in cmap if 0x3000 <= cp <= 0x303F or 0xFF00 <= cp <= 0xFFEF]
    ui = sorted(
        {ord(c) for c in zh_ui_text() if is_cjk(ord(c)) and ord(c) in cmap}
        | set(cjk_punct)
    )
    pieces = [("latin", latin), ("symbols", symbols), ("ui", ui)]
    taken = set(latin) | set(symbols) | set(ui)

    hot = [
        ord(c)
        for c, _ in docs_frequency().most_common()
        if ord(c) in cmap and ord(c) not in taken
    ]
    for i in range(0, len(hot), HOT_SIZE):
        pieces.append((f"hot-{i // HOT_SIZE:02d}", sorted(hot[i : i + HOT_SIZE])))
    taken |= set(hot)

    rest = [
        ord(c)
        for c in gb2312_chars()
        if ord(c) in cmap and ord(c) not in taken and is_cjk(ord(c))
    ]
    for i in range(0, len(rest), GB_SIZE):
        pieces.append((f"gb-{i // GB_SIZE:02d}", sorted(rest[i : i + GB_SIZE])))
    return pieces


def unicode_range(cps: list[int]) -> str:
    parts, start = [], cps[0]
    for prev, cp in zip(cps, [*cps[1:], None]):
        if cp is None or cp != prev + 1:
            parts.append(f"U+{start:X}" if start == prev else f"U+{start:X}-{prev:X}")
            start = cp if cp is not None else start
    return ", ".join(parts)


def build_piece(src: Path, cps: list[int]) -> bytes:
    font = TTFont(src)
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=cps)
    subsetter.subset(font)
    font.flavor = "woff2"
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()


def main(src_dir: Path) -> None:
    pieces = plan_pieces(set(TTFont(src_dir / "LXGWWenKai-Regular.ttf").getBestCmap()))
    shutil.rmtree(OUT_DIR, ignore_errors=True)
    OUT_DIR.mkdir(parents=True)
    css = [
        "/* Generated by scripts/build-wenkai-fonts.py (ADR 0059). Do not edit by hand. */",
        "/* LXGW WenKai v1.530, SIL OFL 1.1: src/fonts/LICENSE-LXGWWenKai.txt */",
    ]
    total = 0
    for style, slug, weight_range in WEIGHTS:
        src = src_dir / f"LXGWWenKai-{style}.ttf"
        for name, cps in pieces:
            data = build_piece(src, cps)
            total += len(data)
            filename = f"{slug}-{name}.woff2"
            (OUT_DIR / filename).write_bytes(data)
            css.append(
                "@font-face {\n"
                f'  font-family: "{FAMILY}";\n'
                "  font-style: normal;\n"
                f"  font-weight: {weight_range};\n"
                "  font-display: swap;\n"
                f'  src: url("{URL_PREFIX}/{filename}") format("woff2");\n'
                f"  unicode-range: {unicode_range(cps)};\n"
                "}"
            )
    CSS_PATH.write_text("\n".join(css) + "\n", "utf-8")
    sizes = ", ".join(f"{n} {len(c)}" for n, c in pieces[:3])
    print(
        f"{len(pieces)} pieces x {len(WEIGHTS)} weights ({sizes}, ...), {total // 1024} KB total"
    )


if __name__ == "__main__":
    main(Path(sys.argv[1]))
